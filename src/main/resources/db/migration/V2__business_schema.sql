-- Goods identified by TARIC code (10 digits)
CREATE TABLE goods (
    code VARCHAR(10) PRIMARY KEY,
    description TEXT
);

-- TARIC measures
CREATE TABLE measures (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    goods_code VARCHAR(10) NOT NULL REFERENCES goods(code),
    direction TEXT NOT NULL CHECK (direction IN ('import', 'export')),
    action TEXT NOT NULL,
    legal_reference TEXT NOT NULL,
    legal_url TEXT
);

-- Countries concerned by each measure
CREATE TABLE measure_countries (
    measure_id BIGINT NOT NULL REFERENCES measures(id) ON DELETE CASCADE,
    country_code VARCHAR(2) NOT NULL,
    PRIMARY KEY (measure_id, country_code)
);

-- Categories associated with measures
CREATE TABLE measure_categories (
    measure_id BIGINT NOT NULL REFERENCES measures(id) ON DELETE CASCADE,
    category TEXT NOT NULL,
    source TEXT NOT NULL,
    PRIMARY KEY (measure_id, category)
);

-- Footnote definitions
CREATE TABLE footnotes (
    code TEXT PRIMARY KEY,
    text TEXT NOT NULL
);

-- Footnotes associated with measures
CREATE TABLE measure_footnotes (
    measure_id BIGINT NOT NULL REFERENCES measures(id) ON DELETE CASCADE,
    footnote_code TEXT NOT NULL REFERENCES footnotes(code),
    PRIMARY KEY (measure_id, footnote_code)
);

-- Search indexes
CREATE INDEX idx_measures_search
    ON measures (goods_code, direction);

CREATE INDEX idx_measure_countries_country
    ON measure_countries (country_code, measure_id);